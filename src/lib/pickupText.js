// ข้อความจุดรับของคำขอรถรับ-ส่งผู้ป่วย — ระบบจองเก็บเป็นสตริงเดียวที่ต่อ "หมู่บ้าน/สถานที่ที่กดเลือก"
// กับ "บ้านเลขที่/จุดสังเกตที่พิมพ์" ด้วย " · " (ดู BookingForm.jsx) สองส่วนนี้ชนกันได้ — ผู้จองกดเลือก
// "หมู่ 3 บ้านทุ่งแค้ว" แล้วช่องจุดสังเกตก็มีคำเดียวกัน (พิมพ์เอง หรือเติมจากหมุดแผนที่) ได้ข้อความ
// "หมู่ 3 บ้านทุ่งแค้ว · หมู่ 3 บ้านทุ่งแค้ว" ขึ้นไปทั้งบนจอเจ้าหน้าที่และบนใบคำขอที่ส่งออก
//
// ตัดเฉพาะส่วนที่ "เหมือนกันทุกตัวอักษร" (เทียบหลังยุบช่องว่างซ้ำ) เก็บส่วนแรกไว้ ไม่ตัดแบบ "ส่วนหนึ่งอยู่ใน
// อีกส่วน" โดยตั้งใจ — เลขหมู่ซ้อนกันได้ ("หมู่ 1" เป็นส่วนหนึ่งของ "หมู่ 10") ตัดแล้วที่อยู่เปลี่ยนความหมาย
// ข้อความที่ซ้ำกันบางส่วน (เช่น ที่อยู่จากหมุดยาวกว่าชื่อหมู่บ้าน) จึงยังอยู่ครบ ให้ผู้ใช้เห็นและแก้เอง
//
// ⚠️ ไฟล์นี้ต้องไม่ import supabase — เทสต์รันด้วย node ตรงๆ

export const PICKUP_SEPARATOR = ' · '

const sameKey = part => part.replace(/\s+/g, ' ')

/** ต่อส่วนของจุดรับ ข้ามส่วนว่างและส่วนที่ซ้ำกับส่วนก่อนหน้า */
export function joinPickup(parts = []) {
  const seen = new Set()
  const kept = []
  for (const raw of parts) {
    const part = String(raw ?? '').trim()
    if (!part) continue
    const key = sameKey(part)
    if (seen.has(key)) continue
    seen.add(key)
    kept.push(part)
  }
  return kept.join(PICKUP_SEPARATOR)
}

/** จุดรับที่เก็บไว้แล้ว (อาจมีส่วนซ้ำจากคำขอเก่า) → ข้อความที่ไม่ซ้ำ */
export function dedupePickup(text) {
  return joinPickup(String(text ?? '').split(PICKUP_SEPARATOR))
}
