export const UNKNOWN_CATEGORY_LABEL = 'เรื่องที่แจ้ง'

const THAI_LETTER = /[ก-๙]/
// หน้าตาแบบรหัส: ตัวพิมพ์เล็ก/ตัวเลข/ขีดล่างล้วน ไม่มีเว้นวรรค (water_repair, cat_mtsubkz2, light)
const CODE_LIKE = /^[a-z][a-z0-9]*(?:_[a-z0-9]+)*$/

/**
 * ชื่อหมวดที่พิมพ์ลงกระดาษได้ — ได้ชื่อที่อ่านเป็นไทยเสมอ
 * - ชื่อมีอักษรไทย → ใช้ตามนั้น (ชื่อที่ อปท. ตั้งเอง ไม่แตะ)
 * - ชื่อว่าง/เป็นรหัสดิบ → ชื่อมาตรฐานของรหัสนั้น ถ้าไม่รู้จักใช้ "เรื่องที่แจ้ง"
 * - ชื่ออื่นที่ไม่ใช่ไทยและไม่เหมือนรหัส (เช่นแอดมินตั้ง "Wi-Fi") → คงไว้ ไม่เดาแทน
 */
export function printableCategoryLabel(code, label) {
  const text = String(label ?? '').trim()
  if (THAI_LETTER.test(text)) return text
  if (!text || text === '—' || CODE_LIKE.test(text)) {
    return STANDARD_CATEGORY_LABEL[code] ?? STANDARD_CATEGORY_LABEL[text] ?? UNKNOWN_CATEGORY_LABEL
  }
  return text
}
