//      (ผู้รับของ/ผู้จ่ายของ/ผู้ให้ยืม) ไปจบคนละตำแหน่ง ดูเหมือนพิมพ์มั่ว
//   2. บรรทัดใต้เส้น (วงเล็บชื่อ/ชื่อตำแหน่ง) อยู่กึ่งกลาง "บนแกนของเส้น" ไม่ใช่กึ่งกลางคอลัมน์
//   3. วงเล็บเว้นชื่อกว้างเท่าเส้นที่อยู่เหนือมัน ไม่งั้นเขียนชื่อ-สกุลลงไม่พอ
//   4. ชื่อ/ตำแหน่งที่ยาวกว่าเส้นต้องล้นออกสองข้างเท่ากัน ห้ามตัดขึ้นบรรทัดใหม่
//      (ชื่อตำแหน่งเต็มยศของ อบต. ยาว ~52mm ตัด 2 บรรทัดแล้วใบสูงขึ้นจนตกหน้า 2)
//
// ⚠️ ทุกค่าในไฟล์นี้วัดจากใบจริงที่เรนเดอร์ด้วย THSarabunPSK 14pt ตามมาตรฐานใน govDocStyle.js
// เปลี่ยนขนาดฟอนต์เมื่อไรต้องวัดใหม่ ห้ามคูณเทียบเอา

/**
 * ความกว้างเส้นลงนามมาตรฐานในบล็อกสองคอลัมน์ (พื้นที่พิมพ์ 160mm หารสองแล้วยังเหลือที่
 * ให้คำว่า "ลงชื่อ" กับคำต่อท้าย) ใบไหนมีช่องลงนามเดี่ยวกลางหน้าใช้เส้นยาวกว่านี้ได้
 * แต่ในบล็อกเดียวกันต้องใช้ค่าเดียวกันทุกจุดเสมอ
 */
export const GOV_SIGN_LINE_W = '40mm'

/** ช่องลงนามเดี่ยวกลางหน้า — ต้นฉบับกระดาษเว้นเส้นยาวกว่าบล็อกสองคอลัมน์ */
export const GOV_SIGN_LINE_W_WIDE = '55mm'

// ความกว้างของจุด '.' และวงเล็บคู่ ที่ THSarabunPSK 14pt (วัดจริง 2569-09-12)
// ใช้คำนวณจำนวนจุดให้วงเล็บกว้างเท่าเส้น — เส้น 40mm ได้ 33 จุด · เส้น 55mm ได้ 47 จุด
const DOT_MM = 1.11
const PARENS_MM = 3.0

/**
 * วงเล็บเว้นชื่อสำหรับเขียนด้วยมือ กว้างเท่าเส้นลงนามที่อยู่เหนือมัน
 *
 * ⚠️ ห้ามกลับไปใช้จำนวนจุดคงที่ — เคยตั้งไว้ 26 จุด (~32mm) ใต้เส้น 40mm ด้วยเหตุผล
 * เรื่องสัดส่วน เจ้าของระบบใช้จริงแล้วแจ้งว่าเขียนชื่อ-สกุลลงไม่หมด (ชื่อไทยเต็มยศ 41-50mm)
 * ความกว้างของช่องเขียนสำคัญกว่าความสวยงาม
 *
 * @param {string} width ความกว้างเส้น เช่น '40mm'
 */
export function govNameBlank(width = GOV_SIGN_LINE_W) {
  const dots = Math.max(4, Math.round((Number.parseFloat(width) - PARENS_MM) / DOT_MM))
  return `(${'.'.repeat(dots)})`
}

/**
 * บล็อกลงนามหนึ่งจุด — "เส้นคือแกน" บรรทัดที่อยู่ใต้มันต้องอยู่กึ่งกลางบนแกนเดียวกันเสมอ
 *
 * ⚠️ ประวัติความผิดพลาดที่ห้ามทำซ้ำ (เจ้าของระบบจับได้จากใบพิมพ์จริงทั้งสองครั้ง):
 *   - เขียนเป็น <p> สองย่อหน้าแยกกัน (บรรทัดบนชิดซ้าย บรรทัดล่าง text-align: center)
 *     → กึ่งกลางที่ได้คือกึ่งกลาง "คอลัมน์" ไม่ใช่แกนของเส้น เพราะเส้นถูกคำว่า "ลงชื่อ"
 *       ดันไปทางขวา ~10mm และคำต่อท้ายกินที่ทางขวาอีก วงเล็บจึงเยื้องซ้ายทุกช่อง
 *   - ตั้ง width: 0 ให้บรรทัดใต้เส้นล้นออกสองข้าง → ความจริงล้นขวาข้างเดียว เยื้อง 16-25mm
 *   - ตั้ง width: 100% → ข้อความที่ยาวกว่ากล่องเริ่มชิดซ้ายแล้วล้นขวา เยื้อง 5mm
 * ที่ถูกคือกล่องแกนกว้างคงที่ (flex: 0 0 auto) ส่วนลูกกว้างพอดีเนื้อหา แล้วให้
 * align-items: center ของแกนเป็นตัวจัดกึ่งกลาง
 *
 * @param {object} args
 * @param {string} [args.width]  ความกว้างแกน = ความกว้างเส้น (ในบล็อกเดียวกันต้องเท่ากันทุกจุด)
 * @param {string} [args.label]  คำนำหน้าเส้น ปกติ 'ลงชื่อ' บางแบบพิมพ์ใช้ '(ลงชื่อ)'
 *   ส่งค่าว่างได้ถ้าต้นฉบับไม่มีคำนำหน้า
 * @param {string} [args.role]   คำต่อท้ายบรรทัดบน เช่น 'ผู้ยืม' (ไม่มีก็เว้นว่าง)
 * @param {string[]} [args.below] บรรทัดใต้เส้น เรียงบนลงล่าง — **escape มาแล้ว**
 * @param {string} [args.signed] ชื่อที่พิมพ์แทนลายมือชื่อ (ยืนยันตัวตนผ่านระบบแล้ว escape มาแล้ว)
 *   มีค่า = ไม่พิมพ์เส้น เพราะลงชื่อแล้ว ไม่ต้องเว้นที่ให้เซ็นซ้ำ
 */
export function govSignRow({ width = GOV_SIGN_LINE_W, label = 'ลงชื่อ', role = '', below = [], signed = '' } = {}) {
  return `<div class="sign-row">
      ${label ? `<span class="sign-label">${label}</span>` : ''}
      <span class="sign-axis" style="width:${width}">
        <!-- ⚠️ ต้องมี &nbsp; ข้างใน — span ว่างที่มีแต่ border-bottom สูง 0 พอเอามาวางใน
             flex column แล้วเส้นจะลอยทับบรรทัดวงเล็บ ไม่ได้เป็นบรรทัดของตัวเอง -->
        ${signed
          ? `<span class="sign-signed">${signed}</span>`
          : '<span class="sign-line">&nbsp;</span>'}
${below.map(text => `        <span class="sign-below">${text}</span>`).join('\n')}
      </span>
      ${role ? `<span class="sign-role">${role}</span>` : ''}
    </div>`
}

/**
 * CSS ของช่องลงนาม — ใส่ในบล็อก <style> ของทุกใบที่ใช้ govSignRow()
 * ห้ามเขียนกฎของ .sign-* ซ้ำในไฟล์ปลายทาง (ยกเว้นระยะห่างรอบบล็อกซึ่งเป็นเรื่องของใบนั้น)
 */
export function govSignBlockCss() {
  return `
  /* ── ช่องลงนามมาตรฐาน (govSignBlock.js) ── */
  .sign-row { display: flex; align-items: flex-start; }
  /* ⚠️ flex: 0 0 auto + ความกว้างคงที่จาก inline style — ห้ามให้กล่องแกนโตตามเนื้อหา
     ถ้าปล่อยให้โต ชื่อตำแหน่งที่ยาวกว่าเส้นจะดันแกนกว้างขึ้น เส้นก็ยืดตาม แล้วเส้นในแต่ละ
     บล็อกยาวไม่เท่ากันอีก คำต่อท้ายก็ไม่ตรงแนว (เคยวัดได้ 40 vs 50mm) */
  .sign-axis { display: flex; flex-direction: column; align-items: center; flex: 0 0 auto; }
  /* กว้างเต็มกล่องแกนเสมอ ความกว้างจริงมาจาก inline style ของ .sign-axis */
  .sign-line { border-bottom: 1px dotted #000; display: block; width: 100%; }
  /* ⚠️ nowrap เฉพาะป้ายกำกับสองข้าง ห้ามครอบทั้งแถว — ชื่อตำแหน่งเต็มยศกว้างกว่าคอลัมน์
     ถ้าห้ามตัดบรรทัดทั้งแถว กล่องจะดันล้นขอบขวากระดาษ */
  /* ⚠️ .sign-label ไม่มี margin ขวา — ระยะระหว่าง "ลงชื่อ" กับหัวเส้นมาจากช่องว่างที่ต้นฉบับ
     กระดาษเว้นไว้ในตัวอักษรเอง ใส่ margin เพิ่มแล้วเส้นจะสั้นลงจากที่ไล่ไว้ทุกใบ */
  .sign-label, .sign-role { white-space: nowrap; }
  .sign-role { margin-left: 1mm; }
  /* บรรทัดใต้เส้น (วงเล็บชื่อ / ชื่อตำแหน่ง) — ต้องกึ่งกลางบนแกนของเส้นเสมอ
     ⚠️ ห้ามใส่ width ให้บรรทัดนี้ ไม่ว่า 0 หรือ 100% ผิดมาแล้วทั้งสองแบบ (ดู govSignRow)
     เหตุที่ต้อง nowrap: ปล่อยให้ตัด 2 บรรทัดแล้วใบสูงขึ้น ~6mm ต่อจุด จนตกหน้า 2 */
  .sign-below { display: block; text-align: center; white-space: nowrap; overflow: visible; }
  /* ลายมือชื่ออิเล็กทรอนิกส์ — ตัวหนาให้เห็นว่าเป็นการลงชื่อ ไม่ใช่ชื่อที่พิมพ์ซ้ำเฉยๆ */
  .sign-signed { display: block; text-align: center; white-space: nowrap; font-weight: 700; }
  /* .sign-row เป็น flex จึงจัดกลางหน้าด้วย text-align ของพ่อไม่ได้ ต้อง justify-content */
  .center-row .sign-row { justify-content: center; }
  /* ต้นฉบับกระดาษย่อหน้าช่องลงนามเข้าไปจากขอบบล็อก ไม่ได้ชิดซ้ายสุด */
  .sign-indent { padding-left: 6mm; }
  .sign-block { break-inside: avoid; page-break-inside: avoid; }`
}
