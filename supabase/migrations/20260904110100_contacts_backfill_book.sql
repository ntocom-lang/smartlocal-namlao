-- ย้ายรายการที่ไม่ใช่เหตุด่วนไปสมุด "ทำเนียบเบอร์โทรสำคัญ" ครั้งเดียว
--
-- แยกไฟล์จาก ADD COLUMN เพราะอ้างคอลัมน์ book ที่เพิ่งเพิ่มใน statement เดียวกันจะได้ 42703
--
-- ย้ายเฉพาะ 2 หมวด:
--   government = หน่วยงานราชการ (ที่ว่าการอำเภอ สำนักงานที่ดิน ศูนย์ดำรงธรรม)
--   leader     = ผู้นำท้องถิ่น (กำนัน ผู้ใหญ่บ้าน สมาชิกสภา)
--
-- ที่ "ไม่" ย้ายและเหตุผล:
--   emergency/health/utility = โทรได้ตลอดเวลาจริง ต้องอยู่หน้าสายด่วนต่อไป
--   other = เดาไม่ได้ว่าเป็นเบอร์ด่วนหรือไม่ ปล่อยไว้ที่สายด่วนแล้วให้แอดมินย้ายเอง
--           เดาผิดทางนี้แค่รก แต่ถ้าเดาแล้วย้ายเบอร์ด่วนออกไป ประชาชนหาไม่เจอตอนฉุกเฉิน
--
-- เงื่อนไข book = 'urgent' กันการทับค่าที่แอดมินตั้งเองไว้แล้ว
-- migration นี้ตั้งใจให้รันครั้งเดียว: ถ้ารันซ้ำหลังแอดมินย้าย government กลับมาสายด่วนเอง
-- ค่าที่แอดมินเลือกจะโดนทับ

update public.emergency_contacts
   set book = 'directory'
 where category in ('government', 'leader')
   and book = 'urgent';
