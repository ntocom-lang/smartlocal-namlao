-- ⚠️ ระยะเวลาเก็บของโมดูลนี้ **ระบบไม่ได้ประกาศตัวเลขไว้** — ข้อความแจ้งการใช้ข้อมูล
-- (patient_booking_settings.privacy_notice) เป็นข้อความที่ อปท. แต่ละแห่งเขียนเอง
-- เวลาสั่งลบจริงต้องส่ง p_retention ให้ตรงกับที่ อปท. นั้นประกาศไว้กับประชาชน
-- ค่าเริ่มต้น 5 ปีตั้งให้เท่ากับของคำร้องเพื่อไม่ให้ระบบมีสองมาตรฐาน **ไม่ใช่ค่าตามระเบียบ**
-- ถ้าจะอ้างระเบียบการเก็บ/ทำลายเอกสารราชการต้องเปิดตัวบทฉบับปัจจุบันตรวจก่อนทุกครั้ง

ALTER TABLE public.patient_bookings
  ADD COLUMN IF NOT EXISTS contact_purged_at timestamptz;

COMMENT ON COLUMN public.patient_bookings.contact_purged_at IS
  'เวลาที่ข้อมูลระบุตัวบุคคล (ชื่อผู้จอง ชื่อผู้เดินทาง เบอร์โทร จุดรับ) ถูกลบตามระยะเวลาเก็บรักษา — NULL = ยังไม่ถึงกำหนด';

-- ช่องเบอร์โทรบังคับรูปแบบ ^0[0-9]{8,9}$ และเป็น NOT NULL จึงเขียนค่าว่างทับตอนลบไม่ได้
-- เปิดให้เก็บสตริงว่างได้เพิ่มหนึ่งค่า (ไม่รับเบอร์รูปแบบอื่น) เพื่อให้ลบข้อมูลได้โดยไม่ต้อง
-- ใส่เบอร์ปลอมซึ่งจะกลายเป็นข้อมูลผิดในระบบ
ALTER TABLE public.patient_bookings
  DROP CONSTRAINT IF EXISTS patient_bookings_phone_check;
ALTER TABLE public.patient_bookings
  ADD CONSTRAINT patient_bookings_phone_check
  CHECK (phone ~ '^0[0-9]{8,9}$' OR phone = '');

-- หมุดเวลาของระยะเก็บรักษา = วันเดินทางจริง (ขากลับถ้ามี ไม่มีก็วันนัด) ไม่ใช่ updated_at
-- เพราะ updated_at ขยับทุกครั้งที่มีใครแตะแถว ทำให้ตัวนับเริ่มใหม่เงียบๆ และไม่ใช่ created_at
-- เพราะคำขอที่จองล่วงหน้านานจะครบกำหนดก่อนได้เดินทางจริง
CREATE INDEX IF NOT EXISTS patient_bookings_retention
  ON public.patient_bookings (municipality_id, status, contact_purged_at);
