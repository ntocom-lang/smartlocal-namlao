-- ยืมข้ามกองในการยื่นครั้งเดียว เฟส 1/2 — คอลัมน์ผูกใบที่มาจากคำขอชุดเดียวกัน
-- ไฟล์ถัดไป 20260911100100 จึงจะสร้าง RPC ที่อ้างคอลัมน์นี้ได้ (กติกาแยกไฟล์ตามเฟส)
--
-- ที่มา: ของที่เปิดให้ยืมของ อปท. กระจายอยู่หลายกองจริง (เต็นท์อยู่สำนักปลัด เครื่องเสียง
-- อยู่กองการศึกษา) แต่ผู้ยืมคนเดียวมักต้องการของจากหลายกองในงานเดียว ของเดิมบังคับให้
-- ยื่นทีละกอง ซึ่งเป็นภาระของประชาชนที่เกิดจากโครงสร้างภายในของ อปท. ไม่ใช่ของเขา
--
-- ⚠️ ทางแก้คือ "ยื่นครั้งเดียว แล้วระบบแตกใบตามกองให้" ไม่ใช่ "ใบเดียวหลายกอง" เพราะ
--   1. ใบ บย. มีช่อง "ไปจากส่วนราชการ" ช่องเดียว และช่องผู้จ่ายของ/ผู้รับคืนชุดเดียว
--      ใบเดียวที่มีของ 3 กองจึงพิมพ์ออกมาแล้วไม่มีใครเซ็นได้ครบ
--   2. สิทธิ์ asset_staff ผูกกับกองตัวเอง การให้หัวหน้ากองหนึ่งอนุมัติของอีกกองเป็นเรื่อง
--      อำนาจหน้าที่ ไม่ใช่เรื่องที่ระบบตัดสินใจแทนได้
-- ผลคือแต่ละใบยังเป็นคำขอปกติที่เดินด้วยกลไกเดิมทุกอย่าง เพิ่มแค่ "รหัสชุด" ไว้อ้างถึงกัน

BEGIN;

ALTER TABLE public.asset_borrow_requests
  ADD COLUMN IF NOT EXISTS batch_id uuid;

COMMENT ON COLUMN public.asset_borrow_requests.batch_id IS
  'รหัสชุดคำขอ — ใบที่ผู้ยืมยื่นครั้งเดียวแล้วระบบแตกตามกองเจ้าของพัสดุ จะได้ค่านี้เท่ากัน '
  'NULL = ยื่นใบเดียวตามปกติ (คำขอทั้งหมดก่อน 2569-09-11 เป็นแบบนี้)';

-- ⚠️ index ต้องมี municipality_id นำหน้า ไม่ใช่ batch_id เดี่ยวๆ — ทุก query ในระบบนี้
-- กรองด้วย อปท. เสมอ และ planner จะเลือก index ที่ขึ้นต้นด้วยคอลัมน์ที่กรองจริงเท่านั้น
CREATE INDEX IF NOT EXISTS asset_borrow_requests_batch_idx
  ON public.asset_borrow_requests (municipality_id, batch_id)
  WHERE batch_id IS NOT NULL;

COMMIT;
