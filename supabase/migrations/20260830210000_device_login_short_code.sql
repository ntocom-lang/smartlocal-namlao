-- QR login: เพิ่มรหัสสั้น 6 หลัก สำหรับกรอกมือแทนการสแกน
--
-- ทำไมต้องมี: การสแกน QR ด้วยแอปกล้องของเครื่องจะเปิดลิงก์ในเบราว์เซอร์เริ่มต้น ซึ่งบน iOS
-- นั้น PWA (ไอคอนหน้าจอโฮม) กับ Safari แยก storage กันคนละส่วน เจ้าหน้าที่ที่ล็อกอินไว้ใน PWA
-- จะกลายเป็นยังไม่ได้ล็อกอินทันทีที่กล้องเปิด Safari ให้ ส่วนการสแกนจากในแอป LINE ก็ติด
-- InAppBrowserGate อีกชั้น — รหัสสั้นเป็นทางที่ใช้ได้ทุกเครื่องโดยไม่ต้องพึ่งกล้องเลย
--
-- code (32 hex) ยังเป็นตัวหลักสำหรับ QR เหมือนเดิม short_code เป็นแค่ทางเข้าเพิ่ม
-- และ "ห้าม" ใช้ short_code ใน claim เด็ดขาด — ฝั่ง PC ยังต้องพิสูจน์ด้วย verifier ตามเดิม
--
-- ความเสี่ยงที่ยอมรับ: เดา short_code ถูกทำได้แค่ 2 อย่าง คือทำให้คำขอของคนอื่นถูกยกเลิก
-- (DoS เล็กน้อย ผู้ใช้กดขอรหัสใหม่ได้) หรืออนุมัติให้ session ของตัวผู้เดาเองไปโผล่บนเครื่อง
-- ของคนอื่น ซึ่งไม่เป็นประโยชน์กับผู้โจมตี การอนุมัติยังต้องมี JWT ของเจ้าหน้าที่จริงและ
-- ต้องแตะเลข 2 หลักให้ตรงกับจอ PC อยู่ดี

ALTER TABLE public.device_login_requests
  ADD COLUMN short_code text;

-- unique ทั้งตารางได้เพราะ cron ลบแถวที่เกิน 1 วันทิ้งอยู่แล้ว จำนวนแถวที่ค้างจึงน้อยมาก
-- เทียบกับพื้นที่รหัส 900,000 ค่า (โอกาสชนต่ำ และ edge function สุ่มใหม่เมื่อชน)
CREATE UNIQUE INDEX idx_device_login_requests_short_code
  ON public.device_login_requests (short_code)
  WHERE short_code IS NOT NULL;
