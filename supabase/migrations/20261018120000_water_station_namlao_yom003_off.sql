-- ปิดสถานีระดับน้ำ YOM003 (หนองม่วงไข่) เฉพาะของเทศบาลตำบลน้ำเลา
--
-- ที่มา: เจ้าของระบบสั่งปิด 2569-10-18 หลังเห็นผลถอดผังน้ำจังหวัดแพร่ + ผังน้ำตำบลน้ำเลา (PR 5.2 · #494)
-- สถานีนี้อยู่ ต.น้ำรัด อ.หนองม่วงไข่ บนแม่น้ำยม ห่างสำนักงานน้ำเลา 14.1 กม. ผังตำบลน้ำเลาไม่ได้วาดสถานีนี้
-- และไม่มีหลักฐานว่าค่าที่สถานีนี้บอกสถานการณ์ในตำบลน้ำเลาได้ (กติกาเดียวกับ Y.38 ที่ปิดไปตั้งแต่
-- 20260928100000 · ค่าที่บอกได้จริงของน้ำเลาคืออ่างแม่คำปอง + สถานีฝน STN0911/RES040)
--
-- ตรวจผลกระทบบน production แล้ว (อ่านอย่างเดียว 2569-10-18): น้ำเลามีสถานีระดับน้ำเปิดอยู่ตัวนี้ตัวเดียว
-- ไม่มีเหตุการณ์น้ำ (water_events) ของน้ำเลาเลย ไม่มีแถวใน water_event_readings/water_village_stations ที่อ้างสถานีนี้
--
-- ผลที่ตามมา: ปิดที่ฐานข้อมูลจุดเดียว ทุกช่องทางตัดสินตรงกัน (เหมือน Y.38)
--   - หน้าสถานการณ์น้ำของน้ำเลา: หัวข้อ "ระดับน้ำในลำน้ำ" + ปุ่มลัด + สถิติบนหัวหน้าหายไป (หน้าเดิมรองรับกรณีไม่มีสถานีระดับน้ำอยู่แล้ว)
--   - แถบเตือนหน้าแรก · Telegram (water-alert-notify) · ตัวจดเหตุการณ์น้ำ เลิกอ่านสถานีนี้ของน้ำเลา
--   - thaiwater-sync เลิกดึงค่า YOM003 ของน้ำเลา (ค่าเก่าที่เก็บไว้ถูกลบโดย cron ล้างข้อมูลที่ 7 วัน)
--
-- ไม่แตะ อปท. อื่น: ทุ่งแค้ว/ตำหนักธรรมใช้ YOM003 เป็นสถานีของตัวเอง (4.8 / 6.6 กม.) · demo เป็นสนามซ้อมที่คงไว้ตามเดิม
-- (เหมือนที่คง Y.38 ไว้) และสถานีฝน YOM003 ของ อปท. อื่นไม่ถูกแตะ (เงื่อนไขระบุ station_type = 'waterlevel')
--
-- ย้อนกลับ: UPDATE ... SET is_active = true ด้วยเงื่อนไขเดียวกัน (ค่าที่ดึงไว้ก่อนปิดไม่หาย ถ้ายังไม่ถูก cron ลบ)

UPDATE public.water_station_config AS c
SET is_active = false, updated_at = now()
FROM public.municipalities AS m
WHERE m.id = c.municipality_id
  AND m.slug = 'namlao'
  AND c.station_type = 'waterlevel'
  AND c.station_code = 'YOM003'
  AND c.is_active;
