-- ยอดรวมตามใบกำกับภาษี/ใบรับสินค้า ที่ปั๊มออกให้จริง
--
-- ทำไมต้องมีคอลัมน์นี้ ทั้งที่มี total_cost อยู่แล้ว
-- total_cost เป็น GENERATED ALWAYS = round(liters * price_per_liter, 2) ซึ่งเป็นยอด
-- "คำนวณย้อน" จากลิตรคูณราคา แต่ปั๊มขายเป็น "ยอดเงิน" — เจ้าหน้าที่สั่งเติมเต็ม 2,000 บาท
-- แล้วปั๊มจ่ายน้ำมันไปเท่าที่ 2,000 บาทซื้อได้ ลิตรที่พิมพ์บนบิลจึงเป็นค่าที่ปัดมาแล้ว
--
-- เคสจริงที่ทำให้ต้องเพิ่มคอลัมน์นี้ (เทศบาลตำบลน้ำเลา 7 ก.ย. 2569)
--   บิล: 50.25 ลิตร x 39.80 บาท = 2,000.00 บาท
--   ระบบ: round(50.25 * 39.80, 2) = 1,999.95 บาท  → ขาดไป 5 สตางค์
-- ไล่แล้วไม่มีคู่ตัวเลขไหนกรอกได้ 2,000.00 พอดี เพราะ liters เก็บ 3 ตำแหน่ง
-- (50.251 -> 1,999.99 · 50.252 -> 2,000.03) และ price_per_liter เก็บ 2 ตำแหน่ง
-- จะได้ก็ต่อเมื่อบิดราคาเป็น 40.00 ซึ่งทำให้ราคา/ลิตรบนสมุดคุมผิดไปจากบิล
--
-- คลาดเคลื่อนหลักสตางค์ต่อรายการ พอรวมทั้งเดือนแล้วยอดไม่ตรงใบกำกับภาษี
-- สอบยันกับฎีกาไม่ผ่าน ต้องนั่งอธิบายทีละบรรทัด
--
-- ปล่อยเป็น NULL ได้ และต้องปล่อยได้ — รายการเก่าทั้งหมดไม่มีค่านี้ ฝั่งแอปจึงตกไปใช้
-- total_cost เหมือนเดิมเมื่อไม่มีค่า ไม่ต้องแก้ข้อมูลเก่าย้อนหลัง

alter table public.fleet_fuel_records
  add column if not exists invoice_total numeric(12,2);

comment on column public.fleet_fuel_records.invoice_total is
  'ยอดรวมตามใบกำกับภาษี/ใบรับสินค้าที่ปั๊มออกให้ (บาท) — ใช้แทน total_cost บนเอกสารพิมพ์เมื่อมีค่า; NULL = ใช้ยอดคำนวณ round(liters*price_per_liter,2)';

-- NOT VALID เพราะแถวเดิมไม่มีค่าให้ตรวจอยู่แล้ว (ทุกแถวเป็น NULL) การ validate ย้อนหลัง
-- จะล็อกตารางโดยไม่ได้อะไรเพิ่ม — constraint มีผลกับ INSERT/UPDATE ใหม่ทันทีอยู่แล้ว
alter table public.fleet_fuel_records
  add constraint fleet_fuel_invoice_total_nonneg
  check (invoice_total is null or invoice_total >= 0) not valid;
