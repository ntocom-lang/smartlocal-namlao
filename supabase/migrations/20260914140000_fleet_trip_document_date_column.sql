-- แบบ 3 (ใบขออนุญาตใช้รถ) บรรทัด "วันที่ ... เดือน ... พ.ศ. ..." บนขวาของใบ เดิมดึงจาก
-- fleet_trips.created_at เสมอ (เวลาที่กดบันทึกจริง) — ตอน "บันทึกการใช้รถย้อนหลัง" เจ้าหน้าที่
-- อยากระบุวันที่ของเอกสารให้ตรงกับเหตุการณ์ที่เกิดขึ้นจริงได้ ไม่ใช่วันที่กดบันทึกในระบบ
--
-- เก็บแยกจาก created_at โดยเจตนา — created_at ต้องคงเป็นเวลาบันทึกจริงเพื่อการตรวจสอบย้อนหลัง (audit)
-- ห้ามให้ผู้ใช้เขียนทับ ส่วน document_date เป็นค่าที่แก้ไขได้ ใช้เฉพาะตอนพิมพ์แบบ 3 เท่านั้น
-- ค่าเป็น NULL ได้ (รายการเดิมทั้งหมด + โมดัลขอใช้รถตามปกติที่ไม่มีช่องนี้) แบบ 3 จะ fallback
-- ไปใช้ created_at เหมือนเดิมทุกจุด (ดู src/lib/fleetTripPrint.js)

ALTER TABLE public.fleet_trips
  ADD COLUMN IF NOT EXISTS document_date date;

COMMENT ON COLUMN public.fleet_trips.document_date IS
  'วันที่ของเอกสารแบบ 3 (แก้ไขได้ตอนบันทึกย้อนหลัง) — NULL แล้ว fallback ไปใช้ created_at ตอนพิมพ์ ไม่ใช่เวลาบันทึกจริงเพื่อ audit ใช้ created_at เท่านั้น';
