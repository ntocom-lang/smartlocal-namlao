-- เดาหมวดของรายการเดิมจากชื่อ ครั้งเดียว — แอดมินแก้ทับได้ทีหลังจากหลังบ้าน
--
-- คีย์เวิร์ดชุดนี้ต้องตรงกับ guessCategory() ใน src/lib/emergencyCategories.js
--
-- ลำดับ CASE สำคัญ: 'leader' ต้องมาก่อน 'government' ไม่งั้น
-- "นายกองค์การบริหารส่วนตำบลทุ่งแค้ว" จะถูกจับด้วยคำว่า "องค์การบริหารส่วน" กลายเป็นหน่วยงานราชการ
-- และ 'utility' มาก่อน 'leader' เพื่อให้ "บริการสิ่งปฏิกูล(สูบส้วม)นาย..." เป็นสาธารณูปโภค ไม่ใช่ผู้นำท้องถิ่น
--
-- ข้อจำกัดที่ยอมรับ: ชื่อคนที่ขึ้นต้นว่า "นายก..." (เช่น "นายกิตติ") จะถูกจัดเป็นผู้นำท้องถิ่น
-- ยอมพลาดทางนี้ดีกว่าพลาดนายก อบต./เทศมนตรี ซึ่งเจอบ่อยกว่ามากในข้อมูลจริง

update public.emergency_contacts set category = case
  when label ~ 'ตำรวจ|สภ\.|กู้ภัย|กู้ชีพ|EMS|ฉุกเฉิน|เจ็บป่วย|ดับเพลิง|ไฟไหม้|มูลนิธิ|ภัยพิบัติ' then 'emergency'
  when label ~ 'โรงพยาบาล|รพ\.|สาธารณสุข|อนามัย|คลินิก|แพทย์|พยาบาล|อสม'                        then 'health'
  when label ~ 'ไฟฟ้า|ประปา|สิ่งปฏิกูล|สูบส้วม|ขยะ|แก๊ส|โทรศัพท์|อินเทอร์เน็ต|ไฟกิ่ง|โคมไฟ'      then 'utility'
  when label ~ 'นายก|กำนัน|ผู้ใหญ่บ้าน|ผู้ช่วยผู้ใหญ่|สารวัตรกำนัน|สมาชิกสภา|ส\.อบต|ปลัด'         then 'leader'
  when label ~ 'อบต|อบจ|เทศบาล|องค์การบริหารส่วน|อำเภอ|จังหวัด|ที่ว่าการ|ภาครัฐ|ราชการ|สำนักงาน|ศูนย์ดำรงธรรม|ที่ทำการ' then 'government'
  else 'other'
end
where category = 'other';
