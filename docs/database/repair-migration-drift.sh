#!/usr/bin/env bash
# ปรับ supabase_migrations.schema_migrations ให้ตรงกับสภาพจริงของ DB
#
# ยืนยันแล้วด้วย docs/database/check-migration-drift-20260828.sql (+ followup)
# ว่า 39 migration นี้ "ผลอยู่ใน DB แล้ว" แค่ไม่ได้ถูกบันทึกว่า applied
# เพราะที่ผ่านมา apply ผ่าน Supabase MCP ซึ่งบันทึกคนละ timestamp กับชื่อไฟล์ local
#
# ไม่รวม 20260816170000_unify_personnel_directory — ตัวนั้นยังไม่เคยรันจริง
# ต้องเช็ค preflight-unify-personnel-directory.sql ก่อน แล้วค่อยรันไฟล์จริง
#
# repair ไม่แตะข้อมูลในตารางแอป แก้แค่ตารางบันทึกประวัติ migration
set -euo pipefail

VERSIONS=(
  20260729171006 20260729171553 20260729182248 20260729183852
  20260730145925 20260730154948 20260730173506
  20260816180000 20260816181000 20260816182000 20260816190000 20260816191000
  20260819120000 20260819130000 20260819140000 20260819150000 20260819160000 20260819170000
  20260820220000 20260820235200 20260821061600 20260821064400
  20260823090000 20260823110000 20260823113000
  20260824100000 20260824120000
  20260826090000 20260826091000
  20260827090000 20260827100000 20260827110000 20260827120000 20260827130000
  20260828090000 20260828100000 20260828110000 20260828120000 20260828130000
)

echo "จะ mark ว่า applied ทั้งหมด ${#VERSIONS[@]} รายการ"
for v in "${VERSIONS[@]}"; do
  echo "  -> $v"
  npx supabase migration repair --status applied "$v"
done

echo ""
echo "เสร็จแล้ว ตรวจผลด้วย: npx supabase migration list --linked"
echo "20260816170000 ยังคงค้างอยู่โดยตั้งใจ (ยังไม่เคยรันจริง)"
