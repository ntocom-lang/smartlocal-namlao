-- ดูว่า 25 remote version ที่ไม่มีไฟล์ local นั้น "คือ migration อะไร"
--
-- ที่มา: migration เหล่านี้ถูก apply ผ่าน Supabase MCP (apply_migration) ซึ่งบันทึกด้วย
-- timestamp ที่ server สร้างตอนนั้น ไม่ใช่ชื่อไฟล์ local — แต่คอลัมน์ name ยังเก็บชื่อที่
-- ส่งเข้าไปตอน apply ไว้ จึงใช้จับคู่กลับไปหาไฟล์ local ได้
--
-- ทำไมต้องตรวจก่อน: supabase CLI แนะนำให้ repair --status reverted ทั้ง 25 ตัว
-- ซึ่งคือ "ลบบันทึกว่ามันเคยรัน" ออกจากตารางประวัติ ทำได้ก็ต่อเมื่อยืนยันแล้วว่าแต่ละตัว
-- ซ้ำกับไฟล์ local ที่เพิ่ง mark applied ไป ถ้าตัวไหนไม่ซ้ำ = มี DDL ที่อยู่ใน DB จริง
-- แต่ไม่มีไฟล์ต้นทางใน repo เลย (ต้อง db pull มาเก็บก่อน ไม่งั้นสร้าง DB ใหม่จะไม่เหมือนเดิม)
--
-- รันได้ซ้ำ ไม่แก้ไขข้อมูลใดๆ

SELECT
  version,
  name,
  -- ดูคำสั่งแรกพอให้เดาออกว่าแตะอะไร (ตัดให้สั้นกันตาราง overflow)
  left(regexp_replace(array_to_string(statements, ' '), '\s+', ' ', 'g'), 160) AS first_statements
FROM supabase_migrations.schema_migrations
WHERE version IN (
  '20260816130620','20260816131618','20260816131712','20260816152754','20260816153459',
  '20260816153625','20260818235249','20260819011437','20260819013749','20260819014059',
  '20260819015103','20260819021151','20260819063038','20260823083117','20260823091022',
  '20260823091727','20260823232242','20260825114813','20260825114839','20260825122134',
  '20260825155004','20260826001846','20260826005737','20260826022311','20260826024615'
)
ORDER BY version;
